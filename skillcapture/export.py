"""
Convert a validated Procedure into a Markdown string for download.
"""

from __future__ import annotations

from skillcapture.schema import Procedure, ProcedureStep, SourceRef


def procedure_to_markdown(proc: Procedure) -> str:
    lines: list[str] = []

    lines.append(f"# {proc.title}")
    lines.append("")
    lines.append(proc.overview)
    lines.append("")

    # Tools & materials
    if proc.tools_and_materials:
        lines.append("## Tools and Materials")
        for item in proc.tools_and_materials:
            lines.append(f"- {item}")
        lines.append("")

    # General warnings
    if proc.general_warnings:
        lines.append("## ⚠️ General Warnings")
        for w in proc.general_warnings:
            lines.append(f"- {w}")
        lines.append("")

    # Steps
    lines.append("## Procedure Steps")
    lines.append("")
    for step in proc.steps:
        _render_step(lines, step)

    # Missing info
    if proc.missing_information:
        lines.append("## ❓ Missing Information")
        for item in proc.missing_information:
            lines.append(f"- {item}")
        lines.append("")

    # Contradictions
    if proc.contradictions:
        lines.append("## ⚡ Contradictions Between Sources")
        for item in proc.contradictions:
            lines.append(f"- {item}")
        lines.append("")

    # Unresolved questions
    if proc.unresolved_questions:
        lines.append("## 🔍 Unresolved Questions")
        for item in proc.unresolved_questions:
            lines.append(f"- {item}")
        lines.append("")

    # Checklist
    if proc.completion_checklist:
        lines.append("## ✅ Completion Checklist")
        for item in proc.completion_checklist:
            lines.append(f"- [ ] {item}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by SkillCapture — Hacktoberfest x MOSS Hack Day Udupi 2026*")

    return "\n".join(lines)


def _render_step(lines: list[str], step: ProcedureStep) -> None:
    inferred_badge = " *(inferred)*" if step.is_inferred else ""
    lines.append(f"### Step {step.step_number}: {step.title}{inferred_badge}")
    lines.append("")
    lines.append(step.instruction)
    lines.append("")

    # Source evidence
    if step.sources:
        lines.append("**Evidence:**")
        for src in step.sources:
            lines.append(f"  {_render_source(src)}")
        lines.append("")

    # Warnings
    if step.warnings:
        for w in step.warnings:
            lines.append(f"> ⚠️ {w}")
        lines.append("")

    # Checkpoint
    if step.checkpoint:
        lines.append(f"**Checkpoint:** {step.checkpoint}")
        lines.append("")

    # Uncertainty note
    if step.uncertainty_note:
        lines.append(f"> 🔶 *Uncertainty: {step.uncertainty_note}*")
        lines.append("")


def _render_source(src: SourceRef) -> str:
    parts = [f"[{src.kind.upper()}]"]
    if src.image_id:
        parts.append(f"Image: `{src.image_id}`")
    if src.page_ref:
        parts.append(f"Page: {src.page_ref}")
    if src.transcript_timestamp:
        parts.append(f"@ {src.transcript_timestamp}")
    if src.quote:
        parts.append(f'— "{src.quote}"')
    return " ".join(parts)
